import os
from pathlib import Path
import stat
from typing import TYPE_CHECKING, Final

from pydantic import BaseModel, ConfigDict, JsonValue, ValidationError

from . import cleanup


if TYPE_CHECKING:
    from collections.abc import Iterable


PATHS: Final = (
    ".venv",
    "node_modules",
    "python/.venv",
    "packages/standards/.venv",
    "typescript/node_modules",
    "apps/docs/node_modules",
)
MAX_ENTRIES: Final = 65536
MARKERS: Final = (".modules.yaml", ".yarn-state.yml", ".package-lock.json")
PRIVATE: Final = frozenset(
    {
        ".npmrc",
        ".pypirc",
        ".netrc",
        ".ssh",
        ".aws",
        ".config",
        ".codex",
        ".claude",
        ".t3",
        "auth.json",
        ".credentials.json",
        "credentials.db",
        "access_tokens.db",
        "application_default_credentials.json",
        "hosts.yml",
        "Preferences",
        "Local State",
        "Cookies",
        "Login Data",
        "History",
        "Bookmarks",
        "profiles.ini",
        "places.sqlite",
        "cookies.sqlite",
        "logins.json",
        "key4.db",
    }
)
VENV_PARTS: Final = frozenset(
    {"bin", "include", "lib", "lib64", "share", "etc", "pyvenv.cfg", "CACHEDIR.TAG", ".gitignore", ".lock"}
)
MARKER_BYTES: Final = 1024 * 1024


class PackageLock(BaseModel):
    model_config = ConfigDict(strict=True, extra="ignore")
    packages: dict[str, JsonValue]


def private(path: Path) -> bool:
    if (
        path.name.partition("-")[0] in PRIVATE
        or cleanup.private_environment_file(path.name)
        or path.name.endswith(".env")
    ):
        return True
    if path.suffix in {".key", ".p12", ".pfx"}:
        return True
    if path.suffix != ".pem":
        return False
    payload = metadata_payload(path)
    return payload is None or b"-----BEGIN CERTIFICATE-----" not in payload or b"PRIVATE KEY" in payload


def aliased(root: Path, target: Path) -> bool:
    relative = target.relative_to(root)
    # Check parents first: looking beneath a looping alias can itself fail.
    return any((root / part).is_symlink() for part in reversed((relative, *relative.parents)) if part != Path())


def resolve_alias(target: Path) -> Path:
    try:
        return target.resolve(strict=True)
    except FileNotFoundError:
        return target.resolve()
    except (OSError, RuntimeError) as error:
        message = "inspection deferred: dependency cache alias cannot be resolved"
        raise ValueError(message) from error


def alias_contains(root: Path, alias: Path, target: Path) -> bool:
    if not aliased(root, alias):
        return False
    resolved = resolve_alias(alias)
    return resolved.is_relative_to(target) or target.is_relative_to(resolved)


def shared(roots: Iterable[Path], target: Path) -> bool:
    for root in roots:
        cleanup.inspection_check()
        if alias_contains(root.parent, root, target):
            return True
        if root.is_symlink():
            continue
        if any(alias_contains(root, root / relative, target) for relative in PATHS):
            return True
    return False


def marker(path: Path) -> bool:
    try:
        metadata = path.lstat()
    except FileNotFoundError:
        return False
    return stat.S_ISREG(metadata.st_mode) and 0 < metadata.st_size <= MARKER_BYTES


def metadata_payload(path: Path) -> bytes | None:
    if not marker(path):
        return None
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC)
    with os.fdopen(descriptor, "rb") as stream:
        metadata = os.fstat(stream.fileno())
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != os.getuid():
            message = "dependency metadata is unsafe"
            raise ValueError(message)
        payload = stream.read(MARKER_BYTES + 1)
    return payload if len(payload) <= MARKER_BYTES else None


def venv_installed(target: Path) -> bool:
    payload = metadata_payload(target / "pyvenv.cfg")
    if payload is None or any(entry.name not in VENV_PARTS for entry in target.iterdir()):
        return False
    return b"home = " in payload and b"include-system-site-packages = " in payload


def native_marker(target: Path, name: str) -> bool:
    payload = metadata_payload(target / name)
    if payload is None:
        return False
    if name == ".package-lock.json":
        try:
            PackageLock.model_validate_json(payload)
        except ValidationError:
            message = "unrecognized native package lock metadata"
            raise ValueError(message) from None
        return True
    if name == ".yarn-state.yml":
        return payload.startswith(b"# Warning: This file is automatically generated.") and b"__metadata:" in payload
    lines = payload.splitlines()
    return any(line.startswith(b"layoutVersion: ") for line in lines) and any(
        line.startswith(b"packageManager: pnpm@") for line in lines
    )


def native_package(entry: Path) -> bool:
    cleanup.inspection_check()
    if entry.name in {*MARKERS, ".bin", ".pnpm", ".store"} or entry.is_symlink():
        return True
    if not entry.is_dir() or entry.name.startswith("."):
        return False
    packages = entry.iterdir() if entry.name.startswith("@") else (entry,)
    for package in packages:
        cleanup.inspection_check()
        if not package.is_symlink() and not marker(package / "package.json"):
            return False
    return True


def installed(target: Path) -> bool:
    # Restore the native managed-environment formats used by the previous
    # cleaner. Never execute an interpreter, package script or editable source.
    if target.name == ".venv":
        recognized = venv_installed(target)
    else:
        recognized = any(native_marker(target, name) for name in MARKERS) and all(
            native_package(entry) for entry in target.iterdir()
        )
    return recognized and not cleanup.generated_source(target)
